"""
Page 3: Player Analytics.
Batting leaderboards, bowling efficiency metrics, Player of the Match honors, and multidimensional player comparisons.
"""

import streamlit as st
import pandas as pd
from src.dashboard.data_loader import load_table
from src.dashboard.components.kpi_cards import render_kpi_card
from src.dashboard.components.chart_helpers import (
    create_horizontal_bar_chart,
    create_scatter_plot,
)
from src.dashboard.config import THEME_COLORS


def render():
    st.title("⚡ Individual Player Analytics")
    st.markdown(
        "<div style='color: #526581; font-size: 0.95rem; margin-bottom: 1rem;'>"
        "Individual masterminds: batting run charts, bowling wicket tallies, and match-winner distributions."
        "</div>",
        unsafe_allow_html=True,
    )

    # Coverage Scope Notice
    st.markdown(
        """
        <div class="info-banner">
            <b>🎯 Analytical Coverage Scope:</b> The metrics below represent the Top-20 career leaderboards generated by PySpark and Spark SQL from the complete 260,920 delivery ball-by-ball dataset.<br>
            <i>Metric Definitions:</i> Batting Strike Rate excludes wides from balls faced. Bowler wickets exclude run outs, retired out/hurt dismissals. Bowling Economy uses legal overs (legal balls / 6) and bowler-conceded runs (excluding byes and leg-byes).
        </div>
        """,
        unsafe_allow_html=True,
    )

    batting_df = load_table("player_batting")
    bowling_df = load_table("player_bowling")
    potm_df = load_table("player_potm")

    # Interactive Controls (Top-N slider and Search)
    ctrl_col1, ctrl_col2 = st.columns([1, 2])
    with ctrl_col1:
        top_n = st.slider("Display Top N Players:", min_value=5, max_value=20, value=10, step=1)
    with ctrl_col2:
        search_query = st.text_input("🔍 Search Player by Name:", placeholder="e.g. Kohli, Dhoni, Chahal, Bumrah")

    # 1. Batting Leaderboard Section
    st.markdown("<div class='section-title'>All-Time Batting Leaderboard</div>", unsafe_allow_html=True)
    filtered_batting = batting_df.copy()
    if search_query:
        filtered_batting = filtered_batting[
            filtered_batting["batter"].str.contains(search_query, case=False, na=False)
        ]
    filtered_batting = filtered_batting.head(top_n)

    if not filtered_batting.empty:
        # Display Table with clean formatting
        bat_display = filtered_batting.copy()
        bat_display["batting_avg"] = bat_display["batting_avg"].apply(lambda x: f"{x:.2f}")
        bat_display["strike_rate"] = bat_display["strike_rate"].apply(lambda x: f"{x:.2f}")
        bat_display.rename(
            columns={
                "batter": "Batter",
                "matches_batted": "Innings/Matches",
                "total_runs": "Runs",
                "balls_faced": "Balls",
                "fours": "4s",
                "sixes": "6s",
                "highest_score": "HS",
                "hundreds": "100s",
                "fifties": "50s",
                "batting_avg": "Average",
                "strike_rate": "Strike Rate",
                "dot_balls_faced": "Dot Balls",
            },
            inplace=True,
        )
        st.dataframe(
            bat_display[
                ["Batter", "Runs", "Innings/Matches", "Average", "Strike Rate", "100s", "50s", "4s", "6s", "HS"]
            ],
            use_container_width=True,
            hide_index=True,
        )

        # Batting Scatter: Strike Rate vs Batting Average
        st.markdown("<div class='section-title'>Batting Impact: Strike Rate vs. Batting Average</div>", unsafe_allow_html=True)
        st.markdown(
            "<span style='color: #526581;'>Scatter quadrant analysis isolating high-volume anchors (high average) from explosive aggressors (high strike rate).</span>",
            unsafe_allow_html=True,
        )
        fig_bat_scatter = create_scatter_plot(
            filtered_batting,
            x_col="strike_rate",
            y_col="batting_avg",
            text_col="batter",
            title="Batting Strike Rate vs. Batting Average",
            x_label="Career Strike Rate (Runs / 100 Balls)",
            y_label="Batting Average (Runs / Dismissal)",
        )
        st.plotly_chart(fig_bat_scatter, use_container_width=True)
    else:
        st.info(f"No batters found matching '{search_query}'.")

    st.markdown("---")

    # 2. Bowling Leaderboard Section
    st.markdown("<div class='section-title'>All-Time Bowling Leaderboard</div>", unsafe_allow_html=True)
    filtered_bowling = bowling_df.copy()
    if search_query:
        filtered_bowling = filtered_bowling[
            filtered_bowling["bowler"].str.contains(search_query, case=False, na=False)
        ]
    filtered_bowling = filtered_bowling.head(top_n)

    if not filtered_bowling.empty:
        bowl_display = filtered_bowling.copy()
        bowl_display["overs"] = bowl_display["overs"].apply(lambda x: f"{x:.1f}")
        bowl_display["economy"] = bowl_display["economy"].apply(lambda x: f"{x:.2f}")
        bowl_display["bowling_avg"] = bowl_display["bowling_avg"].apply(lambda x: f"{x:.2f}")
        bowl_display["bowling_strike_rate"] = bowl_display["bowling_strike_rate"].apply(lambda x: f"{x:.2f}")
        bowl_display.rename(
            columns={
                "bowler": "Bowler",
                "matches_bowled": "Matches",
                "wickets": "Wickets",
                "overs": "Overs",
                "runs_conceded": "Runs Conceded",
                "economy": "Economy Rate",
                "bowling_avg": "Bowling Avg",
                "bowling_strike_rate": "Strike Rate",
                "dot_balls": "Dot Balls",
            },
            inplace=True,
        )
        st.dataframe(
            bowl_display[
                ["Bowler", "Wickets", "Matches", "Overs", "Economy Rate", "Bowling Avg", "Strike Rate", "Dot Balls"]
            ],
            use_container_width=True,
            hide_index=True,
        )

        # Bowling Scatter: Economy Rate vs Total Wickets
        st.markdown("<div class='section-title'>Bowling Control: Economy Rate vs. Total Wickets</div>", unsafe_allow_html=True)
        st.markdown(
            "<span style='color: #526581;'>Scatter quadrant evaluating wicket-taking potency against economic containment.</span>",
            unsafe_allow_html=True,
        )
        fig_bowl_scatter = create_scatter_plot(
            filtered_bowling,
            x_col="economy",
            y_col="wickets",
            text_col="bowler",
            title="Bowling Economy Rate vs. Total Wickets",
            x_label="Economy Rate (Runs / Over)",
            y_label="Career Wickets",
        )
        st.plotly_chart(fig_bowl_scatter, use_container_width=True)
    else:
        st.info(f"No bowlers found matching '{search_query}'.")

    st.markdown("---")

    # 3. Player of the Match Leaderboard
    st.markdown("<div class='section-title'>Player of the Match (POTM) Champions</div>", unsafe_allow_html=True)
    fig_potm = create_horizontal_bar_chart(
        potm_df,
        x_col="potm_awards",
        y_col="player_of_match",
        title="Top 10 Player of the Match Award Winners",
        x_label="Awards Won",
        y_label="Player",
        color_hex=THEME_COLORS["accent_orange"],
    )
    st.plotly_chart(fig_potm, use_container_width=True)
